use crate::{rom::Rom, Ctx};
use anyhow::{ensure, Result};
use std::fmt::Write as _;

const NUM_CAVES: usize = 24;
/// Pointer table: 24 LE u16 -> 12-byte cave parameter records.
const CAVE_PARAM_PTRS: u16 = 0xF233;
const CAVE_PARAM_LEN: usize = 12;
/// 24 records x 8 bytes: 6 password digit bytes + 2 suffix bytes.
const PASSWORDS_ADDR: u16 = 0xA927;
const PASSWORD_LEN: usize = 8;
/// Main 32-byte palette table (4 bg + 4 sprite groups).
const PALETTE_MAIN_ADDR: u16 = 0xA7D2;
/// Additional 32-byte palette table.
const PALETTE_ALT1_ADDR: u16 = 0xEA9E;
/// Additional 32-byte palette table (referenced from NMI path $A35B).
const PALETTE_ALT2_ADDR: u16 = 0xF0CA;
/// Rockford color choices, 16 bytes, indexed by (value & $0F).
/// Spec said $A763, but $A763 is 6502 code; the table is at $A769,
/// confirmed by `LDA $A769,Y` at CPU $A746 and $A7C8.
const ROCKFORD_COLORS_ADDR: u16 = 0xA769;

struct CaveParam {
    spawn_row: u8,
    spawn_col: u8,
    diamond_points: u8,
    diamond_points_bonus: u8,
    diamonds_needed: [u8; 4],
    cave_time: [u8; 4],
}

fn parse_cave_params(rom: &Rom) -> Result<Vec<CaveParam>> {
    let mut out = Vec::with_capacity(NUM_CAVES);
    for i in 0..NUM_CAVES {
        let ptr = rom.cpu_u16(CAVE_PARAM_PTRS + (i * 2) as u16);
        ensure!(
            (0x8000..=0xFFFF - CAVE_PARAM_LEN as u32 as u16).contains(&ptr),
            "cave param pointer {i} out of PRG range: ${ptr:04X}"
        );
        let rec = rom.cpu_slice(ptr, CAVE_PARAM_LEN);
        let mut diamonds_needed = [0u8; 4];
        let mut cave_time = [0u8; 4];
        for lvl in 0..4 {
            diamonds_needed[lvl] = rec[4 + lvl * 2];
            cave_time[lvl] = rec[5 + lvl * 2];
        }
        // rec[0]/rec[1] are Rockford's spawn cell (row, col) — confirmed by the
        // spawn write at $BE80 (`field[row=b0][col=b1] = $E0`). They are NOT
        // amoeba/magic-wall timers (those are hardcoded mechanics).
        out.push(CaveParam {
            spawn_row: rec[0],
            spawn_col: rec[1],
            diamond_points: rec[2],
            diamond_points_bonus: rec[3],
            diamonds_needed,
            cave_time,
        });
    }
    // Sanity: cave 0, difficulty 1 = 10 diamonds / 120 seconds.
    ensure!(
        out[0].diamonds_needed[0] == 10 && out[0].cave_time[0] == 120,
        "sanity failed: cave 0 L1 = {} diamonds / {} s (expected 10/120)",
        out[0].diamonds_needed[0],
        out[0].cave_time[0]
    );
    Ok(out)
}

fn parse_passwords(rom: &Rom) -> Result<[[u8; 8]; NUM_CAVES]> {
    let mut out = [[0u8; 8]; NUM_CAVES];
    for (i, rec) in out.iter_mut().enumerate() {
        rec.copy_from_slice(rom.cpu_slice(PASSWORDS_ADDR + (i * PASSWORD_LEN) as u16, PASSWORD_LEN));
    }
    ensure!(
        out[0][..6].iter().all(|&b| b == 0),
        "sanity failed: password record 0 first 6 bytes not zero: {:02X?}",
        &out[0][..6]
    );
    Ok(out)
}

