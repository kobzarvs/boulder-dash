fn hex_row(bytes: &[u8]) -> String {
    let mut s = String::new();
    for (i, b) in bytes.iter().enumerate() {
        if i > 0 {
            s.push_str(if i % 4 == 0 { ",  " } else { ", " });
        }
        let _ = write!(s, "0x{b:02X}");
    }
    s
}

fn render_data_rs(
    params: &[CaveParam],
    passwords: &[[u8; 8]; NUM_CAVES],
    pal_main: &[u8],
    pal_alt1: &[u8],
    pal_alt2: &[u8],
    rockford: &[u8],
) -> String {
    let mut s = String::new();
    s.push_str("//! Generated by `xtask extract-params` from Boulder_Dash.nes — do not edit.\n\n");

    s.push_str("#[derive(Debug, Clone, Copy)]\npub struct CaveParam {\n");
    s.push_str("    /// Rockford's spawn cell (row, column) on the 40x22 field.\n");
    s.push_str("    pub spawn_row: u8,\n    pub spawn_col: u8,\n");
    s.push_str("    pub diamond_points: u8,\n    pub diamond_points_bonus: u8,\n");
    s.push_str("    /// Diamonds required to open the exit, per difficulty level 1-4.\n");
    s.push_str("    pub diamonds_needed: [u8; 4],\n");
    s.push_str("    /// Cave time in 64-frame units (~1.07 s at 60 Hz), per difficulty 1-4.\n");
    s.push_str("    pub cave_time: [u8; 4],\n}\n\n");

    s.push_str("pub const CAVE_PARAMS: [CaveParam; 24] = [\n");
    for p in params {
        let _ = writeln!(
            s,
            "    CaveParam {{ spawn_row: {}, spawn_col: {}, diamond_points: {}, \
             diamond_points_bonus: {}, diamonds_needed: {:?}, cave_time: {:?} }},",
            p.spawn_row,
            p.spawn_col,
            p.diamond_points,
            p.diamond_points_bonus,
            p.diamonds_needed,
            p.cave_time
        );
    }
    s.push_str("];\n\n");

    s.push_str("pub const PASSWORDS: [[u8; 8]; 24] = [\n");
    for rec in passwords {
        let _ = writeln!(s, "    {:?},", rec);
    }
    s.push_str("];\n\n");

    let _ = writeln!(s, "pub const PALETTE_MAIN: [u8; 32] = [{}];\n", hex_row(pal_main));
    let _ = writeln!(s, "pub const PALETTE_ALT_1: [u8; 32] = [{}];\n", hex_row(pal_alt1));
    let _ = writeln!(s, "pub const PALETTE_ALT_2: [u8; 32] = [{}];\n", hex_row(pal_alt2));
    let _ = writeln!(s, "pub const ROCKFORD_COLORS: [u8; 16] = [{}];\n", hex_row(rockford));

    s.push_str("/// Canonical 2C02 master palette (RGB).\n");
    s.push_str("pub const NES_PALETTE: [[u8; 3]; 64] = [\n");
    for row in NES_PALETTE.chunks(8) {
        s.push_str("    ");
        for c in row {
            let _ = write!(s, "[{}, {}, {}], ", c[0], c[1], c[2]);
        }
        s.push('\n');
    }
    s.push_str("];\n");
    s
}

/// L1 quotas at or above this count are unlikely to be satisfiable from
/// pre-placed diamonds alone; flag them for cross-check against decoded cave
/// maps (butterflies / amoeba produce extra diamonds).
const HIGH_QUOTA_FLAG: u8 = 40;

fn render_dump_txt(
    params: &[CaveParam],
    passwords: &[[u8; 8]; NUM_CAVES],
    pal_main: &[u8],
    pal_alt1: &[u8],
    pal_alt2: &[u8],
    rockford: &[u8],
) -> String {
    let mut s = String::new();
    s.push_str("Boulder Dash NES — cave parameters (from $F233 pointer table)\n");
    s.push_str("spawn = Rockford spawn row/col, need = diamonds required, time = cave time units (64 frames each), per difficulty level 1-4\n\n");
    s.push_str("cave | spawn r  c | pts bonus | L1 need/time | L2 need/time | L3 need/time | L4 need/time | note\n");
    s.push_str("-----+--------------+-----------+--------------+--------------+--------------+--------------+------\n");
    let mut flagged = Vec::new();
    for (i, p) in params.iter().enumerate() {
        let high = p.diamonds_needed[0] >= HIGH_QUOTA_FLAG;
        if high {
            flagged.push((i, p.diamonds_needed[0]));
        }
        let _ = writeln!(
            s,
            " {:2}  |   {:3}  {:3}  | {:3}  {:3}  |  {:3}  {:3}    |  {:3}  {:3}    |  {:3}  {:3}    |  {:3}  {:3}    | {}",
            i,
            p.spawn_row,
            p.spawn_col,
            p.diamond_points,
            p.diamond_points_bonus,
            p.diamonds_needed[0],
            p.cave_time[0],
            p.diamonds_needed[1],
            p.cave_time[1],
            p.diamonds_needed[2],
            p.cave_time[2],
            p.diamonds_needed[3],
            p.cave_time[3],
            if high { "HIGH QUOTA: check vs cave data (butterflies/amoeba?)" } else { "" }
        );
    }
    let _ = writeln!(
        s,
        "\nFlagged caves (L1 quota >= {HIGH_QUOTA_FLAG}): {}",
        if flagged.is_empty() {
            "none".to_string()
        } else {
            flagged
                .iter()
                .map(|(i, q)| format!("cave {i} ({q} diamonds)"))
                .collect::<Vec<_>>()
                .join(", ")
        }
    );

    s.push_str("\nPasswords (24 x 8 bytes at $A927: 6 digit bytes + 2 suffix bytes)\n\n");
    s.push_str("rec | digits        | suffix\n----+---------------+-------\n");
    for (i, rec) in passwords.iter().enumerate() {
        let digits: String = rec[..6]
            .iter()
            .map(|d| if *d <= 9 { (b'0' + d) as char } else { '?' })
            .collect();
        let _ = writeln!(
            s,
            " {:2} | {}  {:02X} {:02X} {:02X} {:02X} {:02X} {:02X} | {:02X} {:02X}",
            i, digits, rec[0], rec[1], rec[2], rec[3], rec[4], rec[5], rec[6], rec[7]
        );
    }

    s.push_str("\nPalettes (hex, NES color indices)\n\n");
    let _ = writeln!(s, "PALETTE_MAIN  ($A7D2): {}", hex_row(pal_main));
    let _ = writeln!(s, "PALETTE_ALT_1 ($EA9E): {}", hex_row(pal_alt1));
    let _ = writeln!(s, "PALETTE_ALT_2 ($F0CA): {}", hex_row(pal_alt2));
    let _ = writeln!(s, "ROCKFORD_COLORS ($A769, table referenced as LDA $A769,Y; spec said $A763 which is code): {}",
        hex_row(rockford));
    s
}

pub fn extract(rom: &Rom, ctx: &Ctx) -> Result<()> {
    let params = parse_cave_params(rom)?;
    let passwords = parse_passwords(rom)?;
    let pal_main = rom.cpu_slice(PALETTE_MAIN_ADDR, 32);
    let pal_alt1 = rom.cpu_slice(PALETTE_ALT1_ADDR, 32);
    let pal_alt2 = rom.cpu_slice(PALETTE_ALT2_ADDR, 32);
    let rockford = rom.cpu_slice(ROCKFORD_COLORS_ADDR, 16);

    let rs = render_data_rs(&params, &passwords, pal_main, pal_alt1, pal_alt2, rockford);
    std::fs::write(ctx.data_dir.join("cave_params.rs"), rs)?;

    let txt = render_dump_txt(&params, &passwords, pal_main, pal_alt1, pal_alt2, rockford);
    std::fs::write(ctx.assets_dir.join("params_dump.txt"), &txt)?;

    let flagged: Vec<usize> = params
        .iter()
        .enumerate()
        .filter(|(_, p)| p.diamonds_needed[0] >= HIGH_QUOTA_FLAG)
        .map(|(i, _)| i)
        .collect();
    println!(
        "params: 24 caves, 24 passwords, 3x32B palettes, 16B rockford colors; high-quota caves: {flagged:?}"
    );
    Ok(())
}
